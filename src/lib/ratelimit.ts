// A general request limiter for the paths that have no authenticated caller.
//
// Login, signup, 2FA and the OTP service were each throttled as they were
// built. Two surfaces were not:
//
//   • /api/widget/message — public, cross-origin, no account behind it, and it
//     runs an LLM turn per accepted message. A site key lifted from a
//     customer's own page source was an unmetered bill and an unbounded write
//     into their conversations.
//
//   • the integration API — key-gated, so not anonymous, but a leaked key could
//     broadcast continuously until a person noticed.
//
// ── Fixed window, not a token bucket ────────────────────────────────────────
//
// A fixed window admits a burst at a window boundary: up to 2x the limit across
// two adjacent windows. A sliding window or a leaky bucket would not, and both
// need either per-request timestamp rows or in-process state.
//
// In-process state is the one that does not work here at all. This runs on
// serverless functions: instances are created and discarded per request, so a
// counter in module scope limits one lambda's view of the world and nothing
// else. Everything shared has to be in the database, which makes each extra
// precision a round trip. The boundary burst is bounded and acceptable; the
// thing being prevented is a sustained flood, not a two-second spike.
//
// ── What happens when the counter cannot be read ────────────────────────────
//
// It does NOT fail closed. That is the same stance as loginthrottle.ts, and
// here it costs nothing: every caller this protects needs the database on its
// very next line — the widget persists the message, the integration API reads
// contacts — so a database that cannot count is a database that is about to
// fail the request anyway. Refusing would convert an outage into a different
// outage, while protecting nothing.
//
// But "not closed" does not have to mean "wide open". A shared outage is
// exactly when an unlimited surface is worth the most to somebody, and until
// recently a Supabase blip meant no limit at all on login attempts, widget
// messages or a leaked API key.
//
// So the fallback is a per-instance counter in module scope. The objection
// above is still true — it is one lambda's view of the world, several
// instances each admit their own allowance, and a cold start forgets
// everything — which is precisely why it is a fallback and not the mechanism.
// It cannot hold a real limit. It can stop one instance from being an open
// firehose, and N x limit is a different kind of number from unlimited.
//
// Every verdict it produces is marked `degraded`, because a caller that cannot
// tell the two apart will eventually report the wrong thing — the health
// board's limiter probe being the first place that would have happened.

import { db } from "./supabase";

export interface Limit {
  limit: number;
  windowSec: number;
}

const envInt = (name: string, fallback: number): number => {
  const n = parseInt(process.env[name] ?? "", 10);
  return Number.isFinite(n) && n > 0 ? n : fallback;
};

// Keyed on the ADDRESS, not the visitor id. The visitor id is generated by the
// browser and sent in the request body, so an attacker varies it freely and a
// per-visitor bucket would hand them a fresh allowance on every message. The
// address is the cheapest thing in the request they do not simply choose.
//
// 60 in five minutes is one message every five seconds sustained. Set above a
// real conversation on purpose: an office behind one NAT address shares it,
// and throttling a customer's actual visitors is a worse outcome than
// admitting a slow script that the per-site ceiling below still catches.
// ── The limits, and why each one is the number it is ──────────────────────
//
// Every one of these defends a surface that costs money per request. None of
// them is a round number for its own sake.

/**
 * /api/contact — one email to the support inbox per request.
 *
 * Six in five minutes is far above any honest use (a person submits once,
 * twice if they mistyped) and low enough that a flood cannot bury a real
 * enquiry before somebody notices.
 */
export const CONTACT_PER_IP: Limit = { limit: 6, windowSec: 300 };

/**
 * /api/waitlist — rows, not email. Cheaper per request, so more generous,
 * but still bounded.
 */
export const WAITLIST_PER_IP: Limit = { limit: 10, windowSec: 300 };

/**
 * The public API, per key: /api/events, /api/broadcast, /api/contacts.
 *
 * Not anonymous — but a leaked key sends WhatsApp messages, which costs money
 * AND sender reputation, and reputation does not come back. Per MINUTE, so a
 * legitimate bulk import still runs while a runaway loop is capped.
 *
 * Overridable because a tenant doing genuine volume should not have to ask
 * for a code change.
 */
export const apiPerKey = (): Limit => ({ limit: envInt("API_KEY_LIMIT", 600), windowSec: 60 });

export interface Verdict {
  allowed: boolean;
  /** Seconds until the window rolls. 0 when allowed. */
  retryAfterSec: number;
  /**
   * The shared counter was unavailable and this answer came from the
   * per-instance fallback. Means "the real limiter is not running", which is
   * not the same as "you are within your limit" — the health board reads this
   * so a working fallback cannot be mistaken for a working limiter.
   */
  degraded?: boolean;
}

const ALLOW: Verdict = { allowed: true, retryAfterSec: 0 };

/** The caller's address, as far as it can be known behind a proxy. */
export function clientIp(req: Request): string {
  const xff = req.headers.get("x-forwarded-for") ?? "";
  return (xff.split(",")[0].trim() || req.headers.get("x-real-ip") || "unknown").slice(0, 60);
}

/**
 * Count this request against `bucket` and say whether it may proceed.
 *
 * The count is incremented even when the answer is no, so a caller sitting on
 * a limit keeps their own window full rather than earning one free request per
 * window the moment they pause.
 */
export async function rateLimit(bucket: string, { limit, windowSec }: Limit): Promise<Verdict> {
  try {
    // db(), not db(): wa_rate_limits is platform-level and carries no
    // RLS policy, so a tenant-confined client would read nothing and the
    // limiter would quietly stop limiting.
    const { data, error } = await db().rpc("rate_limit_hit", {
      p_bucket: bucket.slice(0, 200),
      p_limit: limit,
      p_window_sec: windowSec,
    });
    if (error) {
      // Most likely 0119 has not been applied. Logged loudly rather than
      // swallowed, because "the limiter is not running" must not be silent.
      return degrade(bucket, limit, windowSec, error.message);
    }
    const row = Array.isArray(data) ? data[0] : data;
    if (!row || typeof row.allowed !== "boolean") return degrade(bucket, limit, windowSec, "no verdict returned");
    return { allowed: row.allowed, retryAfterSec: Math.max(0, Number(row.retry_after) || 0) };
  } catch (e) {
    return degrade(bucket, limit, windowSec, e instanceof Error ? e.message : String(e));
  }
}

// ── The fallback ────────────────────────────────────────────────────────────

interface MemWindow { count: number; start: number }

// Module scope, so it lives as long as the lambda instance does and no longer.
const mem = new Map<string, MemWindow>();

// A flood is the only time this fills up, so it has to have a ceiling. 5,000
// live buckets is far more than any real traffic shape produces and small
// enough that holding them costs nothing worth measuring.
const MEM_MAX = 5000;

function memoryHit(bucket: string, limit: number, windowSec: number): Verdict {
  const now = Date.now();
  const windowMs = Math.max(1, windowSec) * 1000;

  if (mem.size >= MEM_MAX) {
    for (const [k, w] of mem) if (now - w.start >= windowMs) mem.delete(k);
    if (mem.size >= MEM_MAX) {
      // Everything is live and we are still over. Drop the oldest half rather
      // than refusing to count: an evicted bucket gets a fresh window, which
      // is the same leniency the whole degraded path already has.
      const oldest = [...mem.entries()].sort((a, b) => a[1].start - b[1].start);
      for (let i = 0; i < Math.ceil(oldest.length / 2); i++) mem.delete(oldest[i][0]);
    }
  }

  const cur = mem.get(bucket);
  const w: MemWindow = !cur || now - cur.start >= windowMs ? { count: 0, start: now } : cur;
  // Counted even when refused, so a caller sitting on the limit keeps their
  // own window full — the same rule the SQL version follows.
  w.count += 1;
  mem.set(bucket, w);

  const allowed = w.count <= limit;
  return {
    allowed,
    retryAfterSec: allowed ? 0 : Math.max(1, Math.ceil((w.start + windowMs - now) / 1000)),
    degraded: true,
  };
}

// An outage plus a flood is the one situation where per-request logging turns
// a database problem into a log-volume problem. One line a minute, carrying
// the count of everything it stands in for.
let lastDegradeLog = 0;
let suppressed = 0;
const DEGRADE_LOG_EVERY_MS = 60_000;

function degrade(bucket: string, limit: number, windowSec: number, why: string): Verdict {
  const now = Date.now();
  if (now - lastDegradeLog >= DEGRADE_LOG_EVERY_MS) {
    const also = suppressed ? ` (+${suppressed} more since the last line)` : "";
    console.error(`[ratelimit] shared counter unavailable — ${why}. Falling back to a per-instance limit; the real limit is NOT being enforced across instances. First seen on bucket ${bucket}${also}`);
    lastDegradeLog = now;
    suppressed = 0;
  } else {
    suppressed += 1;
  }
  return memoryHit(bucket, limit, windowSec);
}

/**
 * All of a request's limits at once, refused on the first that says no.
 *
 * Stated as its own function so a caller with both a per-visitor and a
 * per-site ceiling reads as one decision rather than two nested ifs — and so
 * that the ORDER is fixed: the narrowest bucket is checked first, so a single
 * abusive visitor is attributed to themselves rather than being counted
 * against the whole site.
 */
export async function rateLimitAll(checks: { bucket: string; limit: Limit }[]): Promise<Verdict> {
  for (const c of checks) {
    const v = await rateLimit(c.bucket, c.limit);
    if (!v.allowed) return v;
  }
  return ALLOW;
}
